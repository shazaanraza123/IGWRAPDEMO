const passwordHash = "$2a$08$/sREiTgj59sG4GzzMKQA4.XQvuFokBo.iq1rLzoXAhbmhzo7aZjwq";

function quote(value: string) {
  return `'${value.replaceAll("'", "''")}'`;
}

function jsonLiteral(tag: string, value: unknown) {
  const body = JSON.stringify(value);
  const fence = `$persona_${tag}$`;
  if (body.includes(fence)) throw new Error(`persona ${tag} collides with its SQL fence`);
  return `${fence}${body}${fence}`;
}

function contentInserts(persona: Persona, ownerId: string) {
  const rows: string[] = [];
  const post = persona.main_character_post;
  if (post) {
    rows.push(
      `(${quote(ownerId)}, ${quote(post.id)}, 'post', ${quote(post.posted_at)}, ${quote(post.photo)}, ${post.likes}, ${post.comments}, null, null, null)`,
    );
  }
  const story = persona.most_replied_story;
  if (story) {
    rows.push(
      `(${quote(ownerId)}, ${quote(story.id)}, 'story', ${quote(story.posted_at)}, ${quote(story.photo)}, null, null, null, null, ${story.replies_24h})`,
    );
  }
  if (rows.length === 0) return "";
  return `insert into public.content_items (owner_id, id, kind, posted_at, media_path, likes, comments, shares, saves, replies)
values
  ${rows.join(",\n  ")};\n`;
}

function edgeInserts(persona: Persona, ownerId: string) {
  if (!persona.circle || persona.circle.length === 0) return "";
  const rows = persona.circle.map((friend) => `  (${quote(ownerId)}, ${quote(friend.handle)})`);
  return `insert into public.interaction_edges (user_id, counterpart_handle)
values
${rows.join(",\n")};\n`;
}

export function renderSeedSql(personas: Persona[]) {
  const users: string[] = [];
  const identities: string[] = [];
  const profiles: string[] = [];
  const privacy: string[] = [];
  const children: string[] = [];

  for (const persona of personas) {
    const id = personaIds[persona.persona_key as (typeof personaKeys)[number]];
    if (!id) throw new Error(`no seed id for ${persona.persona_key}`);
    const email = `${persona.persona_key}@personas.invalid`;
    users.push(
      `  ('00000000-0000-0000-0000-000000000000', ${quote(id)}, 'authenticated', 'authenticated', ${quote(email)}, ${quote(passwordHash)}, now(), '{"provider":"email","providers":["email"]}', ${jsonLiteral(`${persona.persona_key}_meta`, { persona_key: persona.persona_key })}::jsonb, now(), now(), '', '', '', '', false)`,
    );
    identities.push(
      `  (${quote(id)}::uuid, ${quote(id)}, 'email', ${jsonLiteral(`${persona.persona_key}_identity`, { sub: id, email })}::jsonb, now(), now(), now())`,
    );
    const avatar = persona.profile.avatar ? quote(persona.profile.avatar) : "null";
    profiles.push(
      `  (${quote(id)}::uuid, ${quote(`catalog.${persona.persona_key}`)}, ${quote(persona.profile.display_name)}, ${avatar}, ${quote(persona.profile.account_type)}, ${persona.profile.is_teen}, ${quote(persona.persona_key)}, ${jsonLiteral(persona.persona_key, persona)}::jsonb)`,
    );
    privacy.push(`  (${quote(id)}::uuid)`);
    children.push(contentInserts(persona, id));
    children.push(edgeInserts(persona, id));
  }

  return `-- Generated by supabase/seed.ts. Synthetic persona templates for local reset.
insert into auth.users (
  instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
  confirmation_token, recovery_token, email_change_token_new, email_change, is_anonymous
)
values
${users.join(",\n")};

insert into auth.identities (user_id, provider_id, provider, identity_data, last_sign_in_at, created_at, updated_at)
values
${identities.join(",\n")};

insert into public.profiles (id, handle, display_name, avatar_path, account_type, is_teen, persona_key, source_document)
values
${profiles.join(",\n")};

insert into public.privacy_settings (user_id)
values
${privacy.join(",\n")};

${children.filter((statement) => statement.length > 0).join("\n")}
`;
}

export async function loadPersonas() {
  const personas: Persona[] = [];
  for (const key of personaKeys) {
    const file = new URL(`../data/personas/${key}.json`, import.meta.url);
    personas.push(parsePersona(JSON.parse(await Deno.readTextFile(file))));
  }
  return personas;
}

if (import.meta.main) {
  const sql = renderSeedSql(await loadPersonas());
  await Deno.writeTextFile(new URL("./seed.sql", import.meta.url), sql);
  console.log("wrote supabase/seed.sql");
}
